/**
 * The vendor's license tool. Runs on the vendor's machine only — it needs the private
 * key, which is never shipped with the app.
 *
 *   npm run license -- keygen                      one time: make the key pair
 *   npm run license -- issue --until 2027-03-31    a license valid to the end of that day
 *   npm run license -- issue --until 1405/12/29    same, with a Jalali date
 *   npm run license -- issue --forever             a permanent license (final handover)
 *   npm run license -- show <file>                 verify and describe a license file
 *
 * `issue` options:
 *   --to "Sazkara"   who it is for (default: Sazkara)
 *   --note "..."     free text carried inside the license
 *   --install        also install it into the database in DATABASE_URL (your own demo)
 *
 * The private key lives in ~/.sazkara-license/private.pem. BACK IT UP. Lose it and no new
 * license can ever be issued for builds already delivered.
 */
import { randomUUID } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { CompactSign, exportPKCS8, exportSPKI, generateKeyPair, importPKCS8 } from 'jose';

import { formatJalali, jalaliToDate, toLatinDigits } from '../lib/dates';
import {
  armorLicense,
  LICENSE_ALG,
  LICENSE_ISSUER,
  verifyLicense,
  type LicenseClaims,
} from '../lib/license/token';

const HOME_DIR = path.join(os.homedir(), '.sazkara-license');
const PRIVATE_KEY = path.join(HOME_DIR, 'private.pem');
const ISSUED_DIR = path.join(HOME_DIR, 'issued');
const PUBLIC_KEY_FILE = path.join(__dirname, '..', 'lib', 'license', 'public-key.ts');

const argv = process.argv.slice(2);
const command = argv[0];

function flag(name: string): string | undefined {
  const i = argv.indexOf(`--${name}`);
  return i >= 0 ? argv[i + 1] : undefined;
}
const has = (name: string) => argv.includes(`--${name}`);

function fail(message: string): never {
  console.error(`\n  ${message}\n`);
  process.exit(1);
}

/** The last instant of a date in Tehran, as the UTC Date. Accepts Gregorian or Jalali. */
function endOfDay(input: string): Date {
  const m = toLatinDigits(input).trim().match(/^(\d{4})[-/](\d{1,2})[-/](\d{1,2})$/);
  if (!m) fail(`Could not read the date "${input}". Use 2027-03-31 or 1405/12/29.`);
  const [y, mo, d] = [Number(m[1]), Number(m[2]), Number(m[3])];

  const startOfDay =
    y < 1700
      ? jalaliToDate(y, mo, d)
      : // Iran has had no DST since 2022, so Tehran is a fixed +03:30.
        new Date(Date.UTC(y, mo - 1, d) - 3.5 * 3600_000);
  return new Date(startOfDay.getTime() + 24 * 3600_000 - 1000);
}

function describe(claims: LicenseClaims): string {
  const exp = claims.exp
    ? `${new Date(claims.exp * 1000).toISOString().slice(0, 10)} (${formatJalali(new Date(claims.exp * 1000))}), end of day Tehran time`
    : 'never (permanent)';
  return [
    `  For:      ${claims.sub}`,
    `  Expires:  ${exp}`,
    `  Issued:   ${new Date(claims.iat * 1000).toISOString().slice(0, 16).replace('T', ' ')} UTC`,
    `  Id:       ${claims.jti}`,
    ...(claims.note ? [`  Note:     ${claims.note}`] : []),
  ].join('\n');
}

async function keygen() {
  if (fs.existsSync(PRIVATE_KEY) && !has('force')) {
    fail(
      `A private key already exists at ${PRIVATE_KEY}.\n` +
        '  Making a new one would make every build you already delivered reject your future\n' +
        '  licenses. If you really mean it, add --force.',
    );
  }
  const { privateKey, publicKey } = await generateKeyPair(LICENSE_ALG, {
    crv: 'Ed25519',
    extractable: true,
  });
  fs.mkdirSync(HOME_DIR, { recursive: true });
  fs.writeFileSync(PRIVATE_KEY, await exportPKCS8(privateKey), { mode: 0o600 });

  const spki = (await exportSPKI(publicKey)).trim();
  fs.writeFileSync(
    PUBLIC_KEY_FILE,
    [
      '/**',
      ' * Generated by `npm run license -- keygen`. The public half of the vendor license key:',
      ' * it can verify a license but cannot create one. Changing it invalidates every license',
      ' * issued so far.',
      ' */',
      `export const LICENSE_PUBLIC_KEY = \`${spki}\`;`,
      '',
    ].join('\n'),
  );

  console.log(`\n  Private key written to ${PRIVATE_KEY}`);
  console.log('  Public key written into lib/license/public-key.ts (rebuild the app to use it).');
  console.log('\n  Copy that private.pem to a USB stick or password manager now.\n');
}

async function install(text: string) {
  // Imported late so `keygen`/`issue` work without a database.
  const { PrismaClient } = await import('@prisma/client');
  const { installLicense } = await import('../lib/license/state');
  const db = new PrismaClient();
  try {
    const result = await installLicense(db, text);
    if (!result.ok) fail(`The database refused the license: ${result.error}.`);
    console.log('  Installed into the database in DATABASE_URL.');
  } finally {
    await db.$disconnect();
  }
}

async function issue() {
  if (!fs.existsSync(PRIVATE_KEY)) fail('No private key yet. Run: npm run license -- keygen');

  const until = flag('until');
  const forever = has('forever');
  if (!until && !forever) fail('Say how long it lasts: --until 2027-03-31, or --forever.');
  if (until && forever) fail('Use either --until or --forever, not both.');

  const now = Math.floor(Date.now() / 1000);
  const claims: LicenseClaims = {
    iss: LICENSE_ISSUER,
    sub: flag('to') ?? 'Sazkara',
    jti: randomUUID(),
    iat: now,
    ...(until ? { exp: Math.floor(endOfDay(until).getTime() / 1000) } : {}),
    ...(flag('note') ? { note: flag('note') } : {}),
  };
  if (claims.exp !== undefined && claims.exp <= now) fail('That date is already in the past.');

  const privateKey = await importPKCS8(fs.readFileSync(PRIVATE_KEY, 'utf8'), LICENSE_ALG);
  const jws = await new CompactSign(new TextEncoder().encode(JSON.stringify(claims)))
    .setProtectedHeader({ alg: LICENSE_ALG, typ: 'SZK-LIC' })
    .sign(privateKey);
  const text = armorLicense(jws);

  // Round-trip through the app's own verifier, so a key mismatch shows up here and not
  // on the customer's server.
  try {
    await verifyLicense(text);
  } catch {
    fail(
      'The license was signed but the app would REJECT it: lib/license/public-key.ts does\n' +
        '  not match your private key. Do not send it.',
    );
  }

  fs.mkdirSync(ISSUED_DIR, { recursive: true });
  const stamp = claims.exp
    ? new Date(claims.exp * 1000).toISOString().slice(0, 10)
    : 'permanent';
  const safeName = claims.sub.replace(/[^\w-]+/g, '_');
  const file = path.join(ISSUED_DIR, `${safeName}-until-${stamp}-${claims.jti.slice(0, 8)}.txt`);
  fs.writeFileSync(file, `${text}\n`);

  console.log(`\n${describe(claims)}\n`);
  console.log(`  Saved to ${file}\n`);
  console.log(text);
  console.log('');

  if (has('install')) await install(text);
}

async function show() {
  const file = argv[1];
  if (!file) fail('Which file? npm run license -- show <file>');
  const text = fs.readFileSync(file, 'utf8');
  try {
    console.log(`\n  Signature OK.\n${describe(await verifyLicense(text))}\n`);
  } catch {
    fail('NOT a valid license for this build (bad signature or damaged text).');
  }
}

const commands: Record<string, () => Promise<void>> = { keygen, issue, show };
const run = commands[command ?? ''];
if (!run) fail('Commands: keygen | issue --until <date> | issue --forever | show <file>');
run().catch((err) => {
  console.error(err);
  process.exit(1);
});
